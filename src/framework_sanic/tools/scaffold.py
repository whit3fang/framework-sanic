"""``framework-sanic new``: generate an integration package.

Generates a connector built on ``RestConnector`` (with the call/SMS logging ports stubbed out),
an in-memory fake of the external API, the connector contract suite wired to it, and optional
feature skeletons with a harness test. The contract tests fail until the connector is
implemented: that is the to-do list. Inside the framework repository the package goes to
``integrations/<name>`` and joins the uv workspace.
"""

