def _title(name: str) -> str:
    return " ".join(p.capitalize() for p in name.split("_"))


def _cls(name: str) -> str:
    return "".join(p.capitalize() for p in name.split("_"))


def framework_root(start: Path) -> Path | None:
    """The framework repository (uv workspace root) containing ``start``, if any."""
    for d in [start, *start.parents]:
        pyproject = d / "pyproject.toml"
        if pyproject.exists() and 'name = "framework-sanic"' in pyproject.read_text():
            return d
    return None


def generate(name: str, path: Path, *, features: list[str], package: str | None = None) -> list[Path]:
    if not NAME.match(name) or keyword.iskeyword(name):
        raise SystemExit(f"invalid name {name!r}: use lowercase letters, digits and _ (e.g. zendesk)")
    for f in features:
        if not NAME.match(f):
            raise SystemExit(f"invalid feature name {f!r}")
    if path.exists() and any(path.iterdir()):
        raise SystemExit(f"{path} already exists and is not empty")
    pkg = package or f"framework_sanic_{name}"
    root = framework_root(path.resolve().parent)
    rel = path.resolve().relative_to(root) if root else path
    v = {
        "name": name,
        "title": _title(name),
        "cls": _cls(name),
        "pkg": pkg,
        "dist": pkg.replace("_", "-"),
        "env": name.upper(),
        "rel": str(rel),
        "feature_hint": "".join(f", FEATURES={name}.{f}" for f in features[:1]),
        "feature_entry_points": (
            '\n[project.entry-points."framework_sanic.features"]\n'
            + "".join(f'"{name}.{f}" = "{pkg}.features.{f}:feature"\n' for f in features)
            if features
            else ""
        ),
        # Inside the framework repository the framework comes from the workspace, not an index.
        "workspace_source": "\n[tool.uv.sources]\nframework-sanic = { workspace = true }\n\n"
        if root
        else "\n",
    }
    files: dict[str, str] = {
        "pyproject.toml": PYPROJECT.substitute(v),
        "README.md": README.substitute(v),
        f"src/{pkg}/__init__.py": INIT.substitute(v),
        f"src/{pkg}/connector.py": CONNECTOR.substitute(v),
        f"tests/fake_{name}_api.py": FAKE_API.substitute(v),
        "tests/conftest.py": CONFTEST.substitute(v),
        f"tests/test_{name}_connector.py": CONTRACT_TEST.substitute(v),
    }
    if features:
        files[f"src/{pkg}/features/__init__.py"] = ""
    for f in features:
        fv = {**v, "feature_name": f"{name}.{f}", "feature_title": _title(f), "feature_cls": _cls(f)}
        files[f"src/{pkg}/features/{f}/__init__.py"] = FEATURE.substitute(fv)
        files[f"tests/test_{name}_{f}.py"] = FEATURE_TEST.substitute(fv)
    written = []
    for rel_path, content in files.items():
        target = path / rel_path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
        written.append(target)
    return written


def main(name: str, path: str | None, features: list[str], package: str | None, install: bool) -> None:
    root = framework_root(Path.cwd())
    target = Path(path) if path else (root / "integrations" / name if root else Path(name))
    written = generate(name, target, features=features, package=package)
    print(f"created {target} ({len(written)} files)")
    dist = (package or f"framework_sanic_{name}").replace("_", "-")
    in_workspace = root is not None and target.resolve().is_relative_to(root / "integrations")
    if install and in_workspace and shutil.which("uv"):
        # Join the workspace's dev group so `uv sync` / `uv run` keep it installed.
        result = subprocess.run(["uv", "add", "--dev", dist], cwd=root, capture_output=True, text=True)
        if result.returncode != 0:
            print(result.stderr, file=sys.stderr)
            raise SystemExit(f"generated, but `uv add --dev {dist}` failed (see above)")
        print(f"installed: added {dist} to the workspace dev group")
    print("next steps:")
    print(f"  1. implement the TODOs in {target}/src/{package or f'framework_sanic_{name}'}/connector.py")
    print(f"  2. uv run framework-sanic check {target}     # the contract tests are your checklist")
    print(f"  3. uv run framework-sanic dev --connector {name}")
