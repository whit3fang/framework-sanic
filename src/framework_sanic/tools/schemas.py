"""Generate the UI api-client types from the Pydantic route models.

Writes ``schemas.json`` (JSON Schema per model) and ``generated.ts`` (TypeScript interfaces) so the
Vue packages never hand-maintain request/response shapes.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from framework_sanic.http.routes import RawResponse, RouteSpec


def _collect_routes() -> list[RouteSpec]:
    from framework_sanic.http.app import CORE_ROUTE_MODULES
    from framework_sanic.http.routes import Router

    router = Router()
    for module in CORE_ROUTE_MODULES:
        router.add_module(module)
    # POST /notes, present when a NoteListener is enabled (the UI checks session.notes).
    from framework_sanic.listeners.base import notes_route
    from framework_sanic.listeners.models import NoteIn, NoteOut

    async def unused(principal: object, note: NoteIn) -> NoteOut:
        raise NotImplementedError

    router.add(notes_route(unused))
    return router.routes


def _ts_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def _ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return _ts_name(schema["$ref"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    for key in ("anyOf", "oneOf", "allOf"):
        if key in schema:
            joiner = " & " if key == "allOf" else " | "
            return joiner.join(_ts_type(s) for s in schema[key])
    t = schema.get("type")
    if isinstance(t, list):
        return " | ".join(_ts_type({**schema, "type": x}) for x in t)
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        return f"Array<{_ts_type(schema.get('items', {}))}>"
    if t == "object" or "properties" in schema:
        if "properties" not in schema:
            extra = schema.get("additionalProperties")
            inner = _ts_type(extra) if isinstance(extra, dict) else "unknown"
            return f"Record<string, {inner}>"
        return _ts_object(schema)
    return "unknown"


def _ts_object(schema: dict[str, Any], indent: str = "  ") -> str:
    required = set(schema.get("required", []))
    lines = ["{"]
    for name, prop in schema.get("properties", {}).items():
        opt = "" if name in required else "?"
        lines.append(f"{indent}{name}{opt}: {_ts_type(prop)};")
    lines.append(indent[:-2] + "}")
    return "\n".join(lines)


def build() -> tuple[dict[str, Any], str]:
    models: dict[str, type[BaseModel]] = {}
    endpoints: list[str] = []
    for r in _collect_routes():
        models[r.input_model.__name__] = r.input_model
        out = r.output_model.__name__ if r.output_model and r.output_model is not RawResponse else "unknown"
        if r.output_model and not issubclass(r.output_model, RawResponse):
            models[r.output_model.__name__] = r.output_model
        endpoints.append(
            f'  {{ method: "{r.method}", path: "{r.path}", auth: "{r.auth}", input: "{r.input_model.__name__}", output: "{out}" }},'
        )
    defs: dict[str, Any] = {}
    for name, model in sorted(models.items()):
        schema = model.model_json_schema(ref_template="#/$defs/{model}")
        defs.update(schema.pop("$defs", {}))
        defs[name] = schema
    ts = ["// GENERATED by `framework-sanic export-schemas` from the Pydantic models. Do not edit.", ""]
    for name, schema in sorted(defs.items()):
        body = (
            _ts_type(schema)
            if schema.get("type") != "object" and "properties" not in schema
            else _ts_object(schema)
        )
        if body.startswith("{"):
            ts.append(f"export interface {name} {body}\n")
        else:
            ts.append(f"export type {name} = {body};\n")
    ts.append("export const ENDPOINTS = [")
    ts.extend(endpoints)
    ts.append("] as const;\n")
    return {"$defs": defs}, "\n".join(ts)


def export(out_dir: str) -> None:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    schemas, ts = build()
    (out / "schemas.json").write_text(json.dumps(schemas, indent=2, sort_keys=True))
    (out / "generated.ts").write_text(ts)
    print(f"wrote {out / 'schemas.json'} and {out / 'generated.ts'}")
